#!/bin/sh
# Builds the web copies and deep-zoom tiles from the originals.
#   images/hq/      high-quality originals (JPEG) of the featured works,
#                   plus their deep-zoom tiles and index.js
#   images/normal/  every other work: full-size PNG originals, and the
#                   web-sized JPEG copy of every work (what the gallery shows)
# Originals are never modified. A work that only has a JPEG in images/normal/
# (no original) is left as it is.
#
# Usage:
#   ./export-images.sh            export every work with an original
#   ./export-images.sh hq_1 ...   export only the listed works
#
# Requires ImageMagick (magick) and libvips (vips).
set -eu

cd "$(dirname "$0")"

# Works opened in the deep-zoom viewer. Add an id here when a work is featured.
TILED="hq_1 hq_2 hq_3"
WEB_MAX=2000

# Path of the original for an id, or nothing if there is none.
original() {
  ls "images/hq/$1.jpg" "images/normal/$1.png" 2>/dev/null | head -n 1
}

mkdir -p images/normal images/hq

if [ "$#" -gt 0 ]; then
  ids="$*"
else
  ids=""
  for f in images/hq/*.jpg images/normal/*.png; do
    [ -e "$f" ] || continue
    ids="$ids $(basename "${f%.*}")"
  done
fi

for id in $ids; do
  src=$(original "$id")
  if [ -z "$src" ]; then
    echo "skip $id: no original found" >&2
    continue
  fi

  magick "$src" -auto-orient -background white -alpha remove -alpha off \
    -resize "${WEB_MAX}x${WEB_MAX}>" -strip -quality 85 -interlace Plane \
    "images/normal/$id.jpg"
  echo "normal $id"

  case " $TILED " in
    *" $id "*)
      vips dzsave "$src" "images/hq/$id" --suffix '.jpg[Q=90]' --tile-size 256 --overlap 1 --strip
      echo "hq     $id"
      ;;
  esac
done

# The viewer reads tile sizes from this file, because browsers block the .dzi XML
# when a page is opened from disk (file://). Regenerated on every run.
{
  echo "// Generated by export-images.sh. Do not edit by hand."
  echo "window.TILE_SIZES = {"
  for id in $TILED; do
    src=$(original "$id")
    [ -n "$src" ] && [ -e "images/hq/$id.dzi" ] || continue
    size=$(magick identify -format '%w %h' "$src")
    echo "  \"$id\": { \"width\": ${size% *}, \"height\": ${size#* }, \"tileSize\": 256, \"overlap\": 1 },"
  done
  echo "};"
} > images/hq/index.js
echo "index  images/hq/index.js"
